class TestPythonGuard(GuardTestCase):
    def test_system_directories_are_refused_even_with_force(self) -> None:
        for bad in ("/", "/etc", "/usr", "/var", "/opt", "/home", "/tmp"):
            with self.subTest(path=bad):
                with self.assertRaises(UnsafePathError):
                    guard_delete_target(Path(bad), kind="profile-output", allow_force=True)

    def test_the_working_directory_and_its_ancestors_are_refused(self) -> None:
        with self.assertRaises(UnsafePathError):
            guard_delete_target(Path.cwd(), kind="bundle-output", allow_force=True)
        with self.assertRaises(UnsafePathError):
            guard_delete_target(Path.cwd().parent, kind="bundle-output", allow_force=True)

    def test_an_unrelated_directory_is_refused_and_survives(self) -> None:
        target = self.make_dir("not-ours")
        (target / "important.txt").write_text("keep me")
        with self.assertRaises(UnsafePathError) as ctx:
            guard_delete_target(target, kind="profile-output")
        self.assertIn("does not look like", str(ctx.exception))
        self.assertTrue((target / "important.txt").is_file())

    def test_force_allows_an_unmarked_directory(self) -> None:
        target = self.make_dir("not-ours")
        self.assertEqual(
            guard_delete_target(target, kind="profile-output", allow_force=True), target)

    def test_a_directory_under_build_is_recognised(self) -> None:
        target = self.make_dir("build", "profile")
        self.assertEqual(guard_delete_target(target, kind="profile-output"), target)

    def test_a_marker_from_a_previous_run_is_recognised(self) -> None:
        target = self.make_dir("somewhere", "out")
        write_marker(target, MARKER_PROFILE, "generated by a test")
        self.assertEqual(guard_delete_target(target, kind="profile-output"), target)

    def test_a_missing_path_is_not_an_error(self) -> None:
        target = self.tmp / "does-not-exist"
        self.assertEqual(guard_delete_target(target, kind="profile-output"), target)

    def test_an_empty_path_is_refused(self) -> None:
        with self.assertRaises(UnsafePathError):
            guard_delete_target(Path(""), kind="profile-output", allow_force=True)

    def test_a_symlink_is_refused(self) -> None:
        real = self.make_dir("build", "real")
        link = self.tmp / "link"
        link.symlink_to(real)
        with self.assertRaises(UnsafePathError):
            guard_delete_target(link, kind="profile-output", allow_force=True)
        self.assertTrue(real.is_dir(), "the symlink target was deleted")

    def test_a_mount_point_is_refused(self) -> None:
        with self.assertRaises(UnsafePathError) as ctx:
            guard_delete_target(Path("/proc"), kind="state-dir", allow_force=True)
        self.assertIn("mount point", str(ctx.exception))

    def test_bundle_output_rules(self) -> None:
        empty = self.make_dir("empty-bundle")
        self.assertEqual(guard_delete_target(empty, kind="bundle-output"), empty)
        full = self.make_dir("full-bundle")
        (full / "something.txt").write_text("data")
        with self.assertRaises(UnsafePathError):
            guard_delete_target(full, kind="bundle-output")
        write_marker(full, MARKER_BUNDLE, "written by a test")
        self.assertEqual(guard_delete_target(full, kind="bundle-output"), full)

    def test_state_dir_rules(self) -> None:
        state = self.make_dir("cowrie")
        (state / "var" / "lib" / "cowrie" / "tty").mkdir(parents=True)
        self.assertTrue(looks_like_state_dir(state))
        self.assertEqual(guard_delete_target(state, kind="state-dir"), state)

        unrelated = self.make_dir("home")
        (unrelated / "notes.txt").write_text("not a honeypot")
        with self.assertRaises(UnsafePathError):
            guard_delete_target(unrelated, kind="state-dir")
        self.assertEqual(guard_delete_target(unrelated, kind="state-dir", allow_force=True),
                         unrelated)


