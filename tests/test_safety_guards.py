class TestShellGuard(GuardTestCase):
    """The same rules, because uninstall.sh cannot import a Python module."""

    def test_repository_layout_is_as_expected(self) -> None:
        self.assertTrue(GUARDS_SH.is_file(), f"{GUARDS_SH} is missing")

    def test_system_and_shared_directories_are_refused(self) -> None:
        for bad in ("/", "/etc", "/opt", "/var", "/home", "/usr"):
            with self.subTest(path=bad):
                proc = run_guard(bad)
                self.assertNotEqual(proc.returncode, 0)
                self.assertIn("refusing", proc.stderr)

    def test_an_unmarked_directory_is_refused_unless_forced(self) -> None:
        target = self.make_dir("unrelated")
        proc = run_guard(str(target))
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("does not look like", proc.stderr)

        forced = run_guard(str(target), force="1")
        self.assertEqual(forced.returncode, 0)
        self.assertEqual(forced.stdout.strip(), str(target))

    def test_a_state_directory_layout_is_accepted(self) -> None:
        state = self.make_dir("state")
        (state / "var" / "lib" / "cowrie" / "tty").mkdir(parents=True)
        proc = run_guard(str(state))
        self.assertEqual(proc.returncode, 0)
        self.assertEqual(proc.stdout.strip(), str(state))

    def test_the_script_cannot_delete_a_path_it_did_not_check(self) -> None:
        """
        The delete must act on the guard's RESOLVED path.

        Before the fix the last line was `rm -rf "$STATE_DIR"`, so the checked
        value and the deleted value could differ (STATE_DIR is overridable in
        /etc/cowrie-logship.env). Asserting on the source is crude, but the
        alternative is running a destructive script as root in a test.
        """
        text = UNINSTALL_SH.read_text(encoding="utf-8")
        self.assertIn("guard_delete_target_state_dir", text)
        self.assertIn('rm -rf "$RESOLVED_STATE_DIR"', text)
        self.assertNotIn('rm -rf "$STATE_DIR"', text)
        self.assertIn("deploy/lib/guards.sh", text)
        # The guard must be sourced, not merely mentioned in a comment.
        self.assertRegex(text, "(?m)^source .*deploy/lib/guards[.]sh")

    def test_every_rm_rf_in_the_scripts_targets_a_checked_or_literal_path(self) -> None:
        findings: list[str] = []
        for script in sorted((ROOT / "deploy").rglob("*.sh")) + sorted((ROOT / "ops").rglob("*.sh")):
            for line in script.read_text(encoding="utf-8").splitlines():
                stripped = line.strip()
                if "rm -rf" not in stripped or stripped.startswith("#"):
                    continue
                findings.append(f"{script.relative_to(ROOT)}: {stripped}")
        self.assertEqual(
            findings, ["deploy/uninstall.sh: rm -rf \"$RESOLVED_STATE_DIR\""],
            "a new recursive delete appeared; give it a guard or explain it here")


class TestGuardConsistency(unittest.TestCase):
    def test_default_state_dir_agrees_across_three_files(self) -> None:
        versions = subprocess.run(
            ["bash", "-c", f'source "{VERSIONS_ENV}"; printf "%s" "$STATE_DIR"'],
            capture_output=True, text=True, timeout=30)
        self.assertEqual(versions.returncode, 0, versions.stderr)
        self.assertEqual(versions.stdout, DEFAULT_STATE_DIR,
                         "shared/safe_paths.py and deploy/versions.env disagree")

        shell = subprocess.run(
            ["bash", "-c", f'source "{GUARDS_SH}"; printf "%s" "$DEFAULT_STATE_DIR"'],
            capture_output=True, text=True, timeout=30)
        self.assertEqual(shell.stdout, DEFAULT_STATE_DIR,
                         "deploy/lib/guards.sh and shared/safe_paths.py disagree")


