#!/usr/bin/env python3
"""
Tests for the delete guards (AUDIT F-03) and the isolation config invariant.

Run from the repository root:

    python3 tests/test_safety_guards.py

Three destructive operations in this package take their target from an
operator-supplied argument, and two of them run as root during installation:

  * realism/build_profile.py --out ...   replaces a directory
  * dashboard/bundle.py     --out ...    replaces a directory
  * deploy/uninstall.sh     --remove     deletes the state directory

The failure this suite exists to prevent is `--out /opt/cowrie` (the state
directory, i.e. the recordings) where the operator meant `build/profile`. The
guard's rule is that a recursive delete must be shown to be this package's own
output, and "not shown" means refuse -- so the tests below are mostly negative:
they assert that plausible-but-wrong paths are refused, with the data intact.

The last class checks the invariant the audit asked for by name:
`forward_redirect` and `forward_tunnel` must be false, because everything the
isolation story claims about port forwarding depends on those two values and
nothing read them.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
for sub in ("shared", "dashboard"):
    p = str(ROOT / sub)
    if p not in sys.path:
        sys.path.insert(0, p)
sys.path.insert(0, str(ROOT / "tests" / "lib"))

from config_check import isolation_config_problems  # noqa: E402
from safe_paths import (DEFAULT_STATE_DIR, MARKER_BUNDLE, MARKER_PROFILE,  # noqa: E402
                        UnsafePathError, guard_delete_target, looks_like_state_dir,
                        write_marker)

GUARDS_SH = ROOT / "deploy" / "lib" / "guards.sh"
UNINSTALL_SH = ROOT / "deploy" / "uninstall.sh"
VERSIONS_ENV = ROOT / "deploy" / "versions.env"
VENV_PYTHON = ROOT / ".venv" / "bin" / "python"


def run_guard(path: str, force: str = "0") -> subprocess.CompletedProcess:
    """Call the shell guard the way uninstall.sh does."""
    script = (f'source "{GUARDS_SH}"\n'
              f'guard_delete_target_state_dir "$1" "$2"\n')
    return subprocess.run(["bash", "-c", script, "guard", path, force],
                          capture_output=True, text=True, timeout=30)


class GuardTestCase(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="guard-test-"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def make_dir(self, *parts: str) -> Path:
        path = self.tmp.joinpath(*parts)
        path.mkdir(parents=True, exist_ok=True)
        return path


